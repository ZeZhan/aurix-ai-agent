MAKEFILE = """# AURIX Project Makefile (auto-generated by AURIX AI Agent)
CROSS_COMPILE = {prefix}
CFLAGS  = -Og -g
USER_SRCS = $(wildcard *.c)
CFG_SRCS = \\
  Configurations/Ifx_Cfg_Ssw.c
LIB_SRCS = \\
  Libraries/iLLD/Port/IfxPort.c
EXTRA_SRCS = {extra}
illd-objs: $(LIB_OBJS)
"""


def fake_make(cwd, env, timeout_s, cancel=None):
    """Stand-in for `make illd-objs`: writes one object and a dependency file per library source."""
    cwd = Path(cwd)
    for source in ("Configurations/Ifx_Cfg_Ssw.c", "Libraries/iLLD/Port/IfxPort.c"):
        obj = cwd / "build" / Path(source).with_suffix(".o")
        obj.parent.mkdir(parents=True, exist_ok=True)
        obj.write_bytes(b"OBJ " + source.encode())
        deps = f"{obj.relative_to(cwd).as_posix()}: {source} Configurations/Ifx_Cfg.h App.h\nApp.h:\n"
        obj.with_suffix(".d").write_text(deps, encoding="utf-8")
    return 0, b"ok"


class SlowMake:
    """A make that runs until it is killed."""

    pid = 4242
    returncode = None

    def __init__(self, *args, **kwargs):
        self.killed = False

    def communicate(self, timeout=None):
        if not self.killed:
            raise subprocess.TimeoutExpired("make", timeout)
        return b"", None

    def kill(self):
        self.killed = True


class BuildCacheTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        compiler = self.root / "toolchain" / "tricore-elf-gcc.exe"
        compiler.parent.mkdir()
        compiler.write_bytes(b"gcc")
        self.prefix = str(compiler)[: -len("gcc.exe")]
        cache_patch = patch.object(build_cache, "CACHE_ROOT", self.root / "cache")
        cache_patch.start()
        self.addCleanup(cache_patch.stop)

    def project(self, name: str, extra: str = "", cflags: str = "-Og -g") -> Path:
        project = self.root / name
        files = {
            "Makefile": MAKEFILE.format(prefix=self.prefix, extra=extra).replace("-Og -g", cflags),
            "Configurations/Ifx_Cfg_Ssw.c": "cfg",
            "Configurations/Ifx_Cfg.h": "#define X 1",
            "Libraries/iLLD/Port/IfxPort.c": "port",
            "Libraries/iLLD/Port/IfxPort.h": "port header",
            "App.h": "app header",
            "Cpu0_Main.c": "main",
        }
        for relative, content in files.items():
            (project / relative).parent.mkdir(parents=True, exist_ok=True)
            (project / relative).write_text(content, encoding="utf-8")
        return project

    def test_key_covers_library_inputs_and_settings_only(self) -> None:
        base = build_cache.fingerprint(self.project("a"))
        self.assertIsNotNone(base)
        same = self.project("b", extra="App/extra.c")
        (same / "Cpu0_Main.c").write_text("different application code", encoding="utf-8")
        (same / "Other.h").write_text("non-shadowing application header", encoding="utf-8")
        self.assertEqual(build_cache.fingerprint(same), base)
        self.assertNotEqual(build_cache.fingerprint(self.project("c", cflags="-O0 -g3")), base)
        changed = self.project("d")
        (changed / "Libraries/iLLD/Port/IfxPort.c").write_text("patched port", encoding="utf-8")
        self.assertNotEqual(build_cache.fingerprint(changed), base)
        shadow = self.project("e")
        (shadow / "IfxPort.h").write_text("shadows the iLLD header via -I.", encoding="utf-8")
        self.assertNotEqual(build_cache.fingerprint(shadow), base)

    def test_makefile_without_cache_target_is_not_cached(self) -> None:
        project = self.project("old")
        makefile = project / "Makefile"
        makefile.write_text(makefile.read_text(encoding="utf-8").replace("illd-objs: $(LIB_OBJS)\n", ""), encoding="utf-8")
        self.assertIsNone(build_cache.fingerprint(project))
        self.assertEqual(build_cache.prepare(project, {}, 60)["status"], "skipped")

    def test_first_project_creates_entry_and_second_reuses_it(self) -> None:
        with patch.object(build_cache, "_run_make", side_effect=fake_make) as make:
            first = build_cache.prepare(self.project("one"), {}, 60)
            second_project = self.project("two")
            second = build_cache.prepare(second_project, {}, 60)
        self.assertEqual(first["status"], "created")
        self.assertEqual(second["status"], "hit")
        self.assertEqual(make.call_count, 1)
        self.assertEqual(second["seededObjects"], 2)
        seeded = second_project / "build/Libraries/iLLD/Port/IfxPort.o"
        self.assertEqual(seeded.read_bytes(), b"OBJ Libraries/iLLD/Port/IfxPort.c")
        self.assertGreaterEqual(seeded.stat().st_mtime, (second_project / "Libraries/iLLD/Port/IfxPort.c").stat().st_mtime)
        self.assertTrue((second_project / "build/Libraries/iLLD/Port/IfxPort.d").is_file())
        self.assertFalse((second_project / "build/Cpu0_Main.o").exists())

    def test_existing_library_objects_are_never_overwritten(self) -> None:
        project = self.project("built")
        (project / "build/Libraries").mkdir(parents=True)
        with patch.object(build_cache, "_run_make", side_effect=fake_make) as make:
            report = build_cache.prepare(project, {}, 60)
        self.assertEqual(report["status"], "skipped")
        make.assert_not_called()

    def test_failed_cache_build_leaves_no_entry(self) -> None:
        with patch.object(build_cache, "_run_make", return_value=(2, b"error")):
            report = build_cache.prepare(self.project("broken"), {}, 60)
        self.assertEqual(report["status"], "failed")
        self.assertEqual(build_cache._entries(), [])
        self.assertFalse((build_cache.CACHE_ROOT / report["key"]).exists())
        self.assertFalse(build_cache._lock_path(report["key"]).exists())
        self.assertFalse((self.root / "broken/build").exists())

    def test_objects_are_compiled_in_the_final_entry_directory(self) -> None:
        # Debug information records the compile directory; it must stay valid after the build.
        with patch.object(build_cache, "_run_make", side_effect=fake_make) as make:
            report = build_cache.prepare(self.project("paths"), {}, 60)
        self.assertEqual(Path(make.call_args.args[0]), build_cache.CACHE_ROOT / report["key"] / "src")
        self.assertTrue((build_cache.CACHE_ROOT / report["key"] / "src" / "Libraries/iLLD/Port/IfxPort.c").is_file())

    def test_entry_being_built_elsewhere_falls_back_to_normal_build(self) -> None:
        project = self.project("busy")
        key = build_cache.fingerprint(project)
        build_cache.CACHE_ROOT.mkdir(parents=True)
        build_cache._lock_path(key).write_text("", encoding="utf-8")
        with patch.object(build_cache, "_run_make", side_effect=fake_make) as make:
            report = build_cache.prepare(project, {}, 60)
        self.assertEqual(report["status"], "failed")
        make.assert_not_called()
        self.assertFalse((project / "build").exists())

    def test_incomplete_entry_is_rebuilt_not_used(self) -> None:
        project = self.project("partial")
        key = build_cache.fingerprint(project)
        leftover = build_cache.CACHE_ROOT / key / "src" / "build" / "Libraries"
        leftover.mkdir(parents=True)
        (leftover / "half.o").write_bytes(b"truncated")
        with patch.object(build_cache, "_run_make", side_effect=fake_make):
            report = build_cache.prepare(project, {}, 60)
        self.assertEqual(report["status"], "created")
        self.assertFalse((project / "build/Libraries/half.o").exists())

    def test_changed_external_header_used_by_library_is_not_reused(self) -> None:
        with patch.object(build_cache, "_run_make", side_effect=fake_make):
            build_cache.prepare(self.project("one"), {}, 60)
            other = self.project("two")
            (other / "App.h").write_text("changed header that a library object includes", encoding="utf-8")
            report = build_cache.prepare(other, {}, 60)
        self.assertEqual(report["status"], "dependency-mismatch")
        self.assertFalse((other / "build").exists())

    def test_old_entries_are_pruned(self) -> None:
        with patch.object(build_cache, "_run_make", side_effect=fake_make):
            for index in range(build_cache.MAX_ENTRIES + 2):
                build_cache.prepare(self.project(f"p{index}", cflags=f"-Og -g -DV={index}"), {}, 60)
        self.assertEqual(len(build_cache._entries()), build_cache.MAX_ENTRIES)

    def test_disabled_by_environment(self) -> None:
        with patch.dict(os.environ, {build_cache.ENVIRONMENT_VARIABLE: "0"}):
            self.assertEqual(build_cache.prepare(self.project("off"), {}, 60)["status"], "skipped")

    @unittest.skipUnless(os.name == "nt", "Windows paths are case-insensitive")
    def test_compiler_path_case_does_not_split_the_cache(self) -> None:
        # A workspace setting gave "c:/Infineon/..." while discovery gave "C:/Infineon/...".
        keys = []
        for name, prefix in (("upper", self.prefix.upper()), ("lower", self.prefix.lower())):
            project = self.project(name)
            makefile = project / "Makefile"
            makefile.write_text(makefile.read_text(encoding="utf-8").replace(self.prefix, prefix), encoding="utf-8")
            keys.append(build_cache.fingerprint(project))
        self.assertIsNotNone(keys[0])
        self.assertEqual(keys[0], keys[1])

    def test_cache_build_is_not_cut_at_the_build_timeout(self) -> None:
        with patch.object(build_cache, "_run_make", side_effect=fake_make) as make:
            build_cache.prepare(self.project("long"), {}, 600)
        self.assertGreaterEqual(make.call_args.args[2], build_cache.MIN_CACHE_BUILD_SECONDS)

    def test_timeout_stops_the_whole_process_tree_and_leaves_no_entry(self) -> None:
        with patch.object(build_cache.subprocess, "Popen", SlowMake), \
                patch.object(build_cache, "MIN_CACHE_BUILD_SECONDS", 0), \
                patch.object(build_cache, "CANCEL_POLL_SECONDS", 0.01), \
                patch.object(build_cache, "kill_process_tree") as kill_tree:
            report = build_cache.prepare(self.project("slow"), {}, 0.05)
        kill_tree.assert_called_once_with(4242)
        self.assertEqual(report["status"], "failed")
        self.assertIn("timed out", report["reason"])
        self.assertFalse((build_cache.CACHE_ROOT / report["key"]).exists())
        self.assertFalse(build_cache._lock_path(report["key"]).exists())

    def test_cancelled_cache_build_stops_make_and_leaves_no_entry(self) -> None:
        # build_run sets the event when the client cancels the request (e.g. its timeout).
        cancel = threading.Event()

        class CancelledWhileRunning(SlowMake):
            def communicate(self, timeout=None):
                cancel.set()
                return super().communicate(timeout)

        project = self.project("cancelled")
        started = time.monotonic()
        with patch.object(build_cache.subprocess, "Popen", CancelledWhileRunning), \
                patch.object(build_cache, "CANCEL_POLL_SECONDS", 0.01), \
                patch.object(build_cache, "kill_process_tree") as kill_tree:
            report = build_cache.prepare(project, {}, 600, cancel)
        self.assertLess(time.monotonic() - started, 5)
        kill_tree.assert_called_once_with(4242)
        self.assertEqual(report["status"], "failed")
        self.assertIn("cancelled", report["reason"])
        self.assertFalse((build_cache.CACHE_ROOT / report["key"]).exists())
        self.assertFalse(build_cache._lock_path(report["key"]).exists())

    def test_cancel_before_make_skips_compiling(self) -> None:
        cancel = threading.Event()
        cancel.set()
        with patch.object(build_cache, "_run_make") as make:
            report = build_cache.prepare(self.project("early"), {}, 600, cancel)
        make.assert_not_called()
        self.assertIn("cancelled", report["reason"])
        self.assertFalse((build_cache.CACHE_ROOT / report["key"]).exists())


class KillProcessTreeTests(unittest.TestCase):
    @unittest.skipUnless(os.name == "nt", "Windows-specific: killing the shell alone leaves its children running")
    def test_children_of_a_shell_are_stopped(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        script = Path(temporary.name) / "parent.py"
        script.write_text(
            "import subprocess, sys, time\n"
            "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(60)'])\n"
            "print(child.pid, flush=True)\n"
            "time.sleep(60)\n",
            encoding="utf-8",
        )
        # Same shape as a build: a shell running a process that starts its own children.
        shell = subprocess.Popen(f'"{sys.executable}" "{script}"', shell=True, stdout=subprocess.PIPE, text=True)
        try:
            child_pid = int(shell.stdout.readline())
            kill_process_tree(shell.pid)
            shell.wait(timeout=30)
            listing = subprocess.run(["tasklist", "/FI", f"PID eq {child_pid}", "/NH"],
                                     capture_output=True, text=True).stdout
            self.assertNotIn(f" {child_pid} ", f" {listing} ")
        finally:
            shell.kill()
            shell.stdout.close()


